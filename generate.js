        content: `这是一份记录：${P.victim}在案发前${["两小时", "四十分钟", "十分钟"][ai]}，经过${pick(P.locations, ai + 2)}。\n记录里被划掉了一行，划痕很新。\n你能看出的只有：被划掉的名字是两个人当中的一个。`
